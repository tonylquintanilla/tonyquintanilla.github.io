def fingerprint(raw):
    return hashlib.md5(raw.replace(b"\r\n", b"\n")).hexdigest()


def main():
    if os.path.basename(os.getcwd()) == "documentation":
        raise SystemExit("ERROR: run this from the GALLERY repo ROOT, next to "
                         "interactive.html -- not from documentation/. "
                         "NOTHING was written.")
    if not (os.path.isfile("interactive.html") and os.path.isfile("daily_run.py")):
        raise SystemExit("ERROR: interactive.html and daily_run.py are not "
                         "here, so this is not the gallery root. NOTHING was "
                         "written.")
    for path in NEW_FILES:
        if os.path.exists(path):
            raise SystemExit("ERROR: %s already exists. If this patch already "
                             "ran, it has nothing left to do. NOTHING was "
                             "written." % path)
    results = []
    for path in sorted(EDITS):
        with open(path, "rb") as handle:
            raw = handle.read()
        got = fingerprint(raw)
        if got != BASE[path]:
            raise SystemExit(
                "ERROR: %s is not the file this patch was built against.\n"
                "       expected %s, found %s. It has changed since\n"
                "       0ffa4518, or this patch has already run.\n"
                "       (Line endings are excluded, so they are not the cause.)\n"
                "       NOTHING was written." % (path, BASE[path], got))
        nl = "\r\n" if b"\r\n" in raw else "\n"
        text = raw.decode("utf-8").replace("\r\n", "\n")
        done = []
        for label, old, new in EDITS[path]:
            if text.count(old) != 1:
                raise SystemExit("ANCHOR FAIL (%s): expected 1 match in %s, "
                                 "found %d. NOTHING was written."
                                 % (label, path, text.count(old)))
            text = text.replace(old, new)
            done.append(label)
        if any(ord(ch) > 127 for ch in text):
            raise SystemExit("ERROR: %s would hold non-ASCII text. NOTHING "
                             "was written." % path)
        results.append((path, text.replace("\n", nl), done))
    if "data/objects_config.json" in EDITS:
        import json
        json.loads([r for r in results if r[0] == "data/objects_config.json"][0][1])
    for path, text, done in results:
        with open(path, "wb") as handle:
            handle.write(text.encode("utf-8"))
        for label in done:
            print("ok  %-40s %s" % (path, label))
    for path, content in sorted(NEW_FILES.items()):
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        print("ok  %s created" % path)
    print("")
    print("patch applied")
    print("")
    print("NEXT:")
    print("  1. Run daily_run.py to rebuild the served cache.")
    print("  2. Run gallery_maintenance_run.py -- expect 23 of 23.")
    print("  3. Move this script into documentation/; commit and push.")
    print("  4. On the phone, ?exhibit=sun: tick the galactic tide.")


if __name__ == "__main__":
    main()
